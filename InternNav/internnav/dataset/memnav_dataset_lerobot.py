"""Dataset + collate_fn for `memnav` (implicit-memory image-goal navigation).

Design (v1, "store the KV cache + recompute the window"):

The frozen LingBot-Map stream is precomputed once (offline, lingbot-map env) by
``scripts/dataset_converters/precompute_lingbot_features.py`` and cached next to
every trajectory as ``videos/chunk-000/lingbot_cache.npz``:

  * ``scale_k`` / ``scale_v``  [L, H, 8, P, d]      full K/V of the 8 scale frames
  * ``anchor_k`` / ``anchor_v`` [T-8, L, H, 6, d]    per-frame 6 special-token K/V
  * ``dino_cls`` [T, 1024]                           context-free DINOv2 CLS token

The memory is the LingBot stream anchored at frame 0.  At a sampled current step
``k`` (with sliding window ``W``) the memory partitions into three disjoint,
contiguous regions:

  scale   frames [0 .. 7]       full K/V        (from scale_k/v)
  history frames [8 .. k-W]     6 special only  (from anchor_k/v)
  window  frames [k-W+1 .. k]   recomputed live (raw RGB, in the policy)

The heavy K/V (scale ~1 GB/traj, anchor history ~100 MB) is therefore **not**
loaded here — that would blow up the collated batch.  This dataset is *light*:
it samples ``(k, k_goal)``, builds the NavDP-style action label + critic, reads
only the small ``dino_cls`` retrieval keys, and emits **pointers** so the policy
does the GPU work per sample.

What the policy does with the pointers (v1 architecture — three soft-gated goal
cross-attention readouts + raw goal descriptor):
  * loads the KV cache (``cache_path``, ``cur_step``) → GCT window-forward →
    current "post-GCA" state + compressed trajectory-memory readout.
  * retrieval is **`dino_cls`-only** for v1 (coarse, frame-level): ``goal_cls``
    vs ``mem_cls`` → top-k frames + retrieval/matchability gates.
  * **dense DINO is recomputed on the fly** (no dense storage): the policy loads
    raw RGB at the current window ``[k-W+1..k]``, the goal frame ``k_goal``, and the
    retrieved frame indices (from ``rgb_dir``) and re-runs the DINO forward for
    the in-FoV and revisit dense cross-attention.
So the dataset emits ``cache_path``, ``rgb_dir``, ``cur_step`` (= k), and
``goal_step`` (= k_goal); everything dense/GCT is computed GPU-side.

Genuine multi-leg structure + multi-positive retrieval label (v2)
-----------------------------------------------------------------
The mp3d revisit data is generated by ``MemNavData/generate_twoleg.py`` as real
two-/three-leg episodes.  Each episode has ``n_legs-1`` **goals** (``B`` = goal 1,
``C`` = goal 2, ...), one per leg switch, written to ``meta/gen_meta.json`` with a
per-goal ``covis_curve``: occlusion-aware co-visibility of that goal view against
*every* prior history frame ``[0..k]`` (index i aligns with global frame i).

Each training sample is therefore an ``(episode, goal j)`` pair, NOT a synthetic
``(k, k_goal)``.  For goal ``j``:
  * current step ``k`` is sampled inside the goal's own leg on every access,
    matching Li Guo's ``3af2c8d`` loader. ``fixed_switch`` remains available to
    reproduce the earlier MemNav checkpoints.
  * ``goal_image`` = the rendered ``goal_{j+1}.jpg`` (a real target view, NOT a
    trajectory frame — so it has no cached CLS; the policy computes ``goal_cls``
    from it via the frozen context-free DINO trunk).
  * action label = the **forward** path of the goal's leg ``k -> goal_step``
    (``goal_step`` = last frame of that leg); ``goal_rel_pose`` = its endpoint.

Retrieval is a **multi-positive** label, thresholded from ``covis_curve`` with the
per-episode thresholds recorded in the meta:
  * positive : ``covis >= covis_pos_hi``  AND index ``>= anchor_margin``
  * negative : ``covis <= covis_pos_lo``  AND index ``>= anchor_margin``
  * ignore   : the band in between, and all frames ``< anchor_margin`` (the stream
    cannot ``goal_append`` a match that early), plus own-leg frames not covered by
    the pre-approach covis curve.
  * ``goal.kind`` is the semantic truth: **revisit** makes ``null`` negative and
    **novel** makes it the sole positive. A revisit with no frame above ``pos_hi``
    is skipped; it must never be silently relabeled as novel.

As in ``3af2c8d``, goal A is also sampled using its trajectory arrival frame as
the target and 14/83-frame glimpse thresholds. This label is explicitly heuristic
because the generator does not provide a covis curve or separate goal-A rendering.

We keep only goals with ``k >= num_scale + window - 1`` so the scale / history /
window regions stay disjoint.
"""

