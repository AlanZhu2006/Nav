class MemNav_Dataset(NavDP_Base_Datset):
    def __init__(
        self,
        root_dirs,
        preload_path=False,
        predict_size=24,
        batch_size=64,
        scene_data_scale=1.0,
        trajectory_data_scale=1.0,
        num_scale=8,
        window_size=8,
        seen_ratio=0.5,
        min_gap=4,
        covis_pos_hi=0.5,
        covis_pos_lo=0.1,
        anchor_margin=None,
        pred_digit=4,
        random_digit=False,
        feature_filename='lingbot_cache.npz',
        feature_root=None,
        rgb_subdir='videos/chunk-000/observation.images.rgb',
        meta_filename='meta/gen_meta.json',
        lingbot_repo='/home/asus/Research/Nav/NavDP/baselines/memnav/lingbot-map',
        image_size=518,
        patch_size=14,
        preprocess_mode='pad',
        repeat=1,
        debug=False,
        **kwargs,
    ):
        # We deliberately do NOT call super().__init__ — the base walk requires
        # depth dirs; memnav only needs parquet (poses), path.ply (critic), the
        # cache npz, and the rgb dir (raw frames for goal/window + lazy matches).
        self.predict_size = predict_size
        self.num_scale = num_scale
        self.window_size = window_size
        self.seen_ratio = seen_ratio      # (unused in v2; kept for signature compat)
        self.min_gap = min_gap            # (unused in v2)
        # covis thresholds: meta values take precedence per-episode; these are the
        # fallbacks for any episode that omits them.
        self.covis_pos_hi = covis_pos_hi
        self.covis_pos_lo = covis_pos_lo
        self.anchor_margin_default = (anchor_margin if anchor_margin is not None
                                      else num_scale + window_size - 1)
        self.meta_filename = meta_filename
        self.pred_digit = pred_digit
        self.random_digit = random_digit
        self.feature_filename = feature_filename
        self.feature_root = feature_root
        self.rgb_subdir = rgb_subdir
        self.batch_size = batch_size
        self.debug = debug
        self.image_size = image_size
        self.patch_size = patch_size
        self.preprocess_mode = preprocess_mode

        # LingBot's exact image preprocessing (square-pad to image_size), so the
        # goal/window images here match what the GCT window-forward + dense DINO
        # forward expect on the GPU.
        import sys
        if lingbot_repo not in sys.path:
            sys.path.insert(0, lingbot_repo)
        from lingbot_map.utils.load_fn import load_and_preprocess_images
        self._load_and_preprocess = load_and_preprocess_images

        self.trajectory_dirs = []
        self.trajectory_data_dir = []      # parquet (extrinsics / intrinsic)
        self.trajectory_afford_path = []   # path.ply (path + obstacle points)
        self.trajectory_feature_path = []  # lingbot_cache.npz
        self.trajectory_rgb_dir = []       # raw rgb frames dir (window recompute)
        # flat (episode, goal) sample index — one entry per goal B/C/... with a
        # precomputed multi-positive retrieval label (see build_retrieval_label).
        self.samples = []
        self.label_stats = Counter()

        for group_dir in sorted(p for p in os.listdir(root_dirs)):
            group_path = os.path.join(root_dirs, group_dir)
            if not os.path.isdir(group_path):
                continue
            all_scene = np.array(sorted(p for p in os.listdir(group_path)))
            if all_scene.shape[0] == 0:
                continue
            sel_scene = all_scene[np.arange(0, all_scene.shape[0], 1 / scene_data_scale).astype(np.int32)]
            for scene_dir in sel_scene:
                scene_path = os.path.join(group_path, scene_dir)
                if not os.path.isdir(scene_path):
                    continue
                all_traj = np.array(sorted(p for p in os.listdir(scene_path)))
                if all_traj.shape[0] == 0:
                    continue
                sel_traj = all_traj[np.arange(0, all_traj.shape[0], 1 / trajectory_data_scale).astype(np.int32)]
                for traj_dir in sel_traj:
                    entire_task_dir = os.path.join(scene_path, traj_dir)
                    if not os.path.isdir(entire_task_dir):
                        continue
                    data_path = os.path.join(entire_task_dir, 'data/chunk-000/episode_000000.parquet')
                    afford_path = os.path.join(entire_task_dir, 'data/chunk-000/path.ply')
                    if self.feature_root:
                        rel = os.path.relpath(os.path.join(entire_task_dir, 'videos/chunk-000'), root_dirs)
                        feat_path = os.path.join(self.feature_root, rel, self.feature_filename)
                    else:
                        feat_path = os.path.join(entire_task_dir, 'videos/chunk-000', self.feature_filename)
                    rgb_dir = os.path.join(entire_task_dir, self.rgb_subdir)
                    meta_path = os.path.join(entire_task_dir, self.meta_filename)
                    if not (os.path.isfile(data_path) and os.path.isfile(feat_path)
                            and os.path.isfile(meta_path)):
                        continue
                    # parse the generator meta -> per-goal samples (covis multi-positive label).
                    goal_samples = self._parse_meta(meta_path, rgb_dir, entire_task_dir)
                    if not goal_samples:
                        continue
                    ti = len(self.trajectory_dirs)
                    self.trajectory_dirs.append(entire_task_dir)
                    self.trajectory_data_dir.append(data_path)
                    self.trajectory_afford_path.append(afford_path)
                    self.trajectory_feature_path.append(feat_path)
                    self.trajectory_rgb_dir.append(rgb_dir)
                    for s in goal_samples:
                        s['traj_idx'] = ti
                        self.samples.append(s)

        self.repeat = max(1, int(repeat))
        n_traj = len(self.trajectory_dirs)
        n_samp = len(self.samples)
        n_rev = sum(1 for s in self.samples if s['goal_kind'] == 'revisit')
        print(f"[MemNav_Dataset] {n_samp} goal-samples across {n_traj} episodes under "
              f"{root_dirs} (revisit={n_rev}, novel={n_samp - n_rev}, repeat={self.repeat})")
        if self.label_stats:
            print(f"[MemNav_Dataset] skipped goal labels: {dict(self.label_stats)}")
        if n_samp == 0:
            raise RuntimeError(
                f"No goal-samples found under {root_dirs}. Need '{self.feature_filename}' "
                f"caches AND '{self.meta_filename}' with per-goal 'covis_curve'. "
                "Did you run precompute_lingbot_features.py on generate_twoleg.py output?"
            )

    # ------------------------------------------------------------------ #
    # meta -> per-goal multi-positive retrieval labels
    # ------------------------------------------------------------------ #
    def _parse_meta(self, meta_path, rgb_dir, traj_dir):
        """Read gen_meta.json and return a list of goal-sample dicts (one per goal
        with a valid covis_curve, cache frame, and goal image)."""
        try:
            meta = json.load(open(meta_path))
        except Exception:
            return []
        goals = meta.get('goals') or []
        switches = meta.get('switches') or []
        n_frames = int(meta.get('n_frames', 0))
        pos_hi = float(meta.get('covis_pos_hi', self.covis_pos_hi))
        pos_lo = float(meta.get('covis_pos_lo', self.covis_pos_lo))
        amargin = int(meta.get('anchor_margin', self.anchor_margin_default))
        lo = self.num_scale + self.window_size          # disjoint scale/history/window
        out = []
        for j, g in enumerate(goals):
            curve = g.get('covis_curve')
            if not curve:
                continue
            curve = np.asarray(curve, dtype=np.float32)
            k = int(curve.shape[0] - 1)                 # current step = switches[j]-1
            if k < lo:
                continue
            # goal image (goal_{j+1}.jpg) + current frame must both exist on disk
            goal_img_path = os.path.join(traj_dir, f'goal_{j + 1}.jpg')
            if not (os.path.isfile(goal_img_path) and os.path.isfile(os.path.join(rgb_dir, f'{k}.jpg'))):
                continue
            # goal_step = last frame of this goal's leg (leg j+1)
            leg_end = int(switches[j + 1]) if (j + 1) < len(switches) else n_frames
            goal_step = leg_end - 1
            if goal_step <= k:                          # need >=1 frame of forward motion
                continue
            label, skip_reason = build_retrieval_label(
                curve, g.get('kind'), pos_hi, pos_lo, amargin)
            if label is None:
                self.label_stats[skip_reason] += 1
                continue
            out.append(dict(goal_j=j, k=k, goal_step=goal_step, goal_img_path=goal_img_path,
                            goal_kind=g.get('kind'), pos_mask=label.pos_mask,
                            neg_mask=label.neg_mask, candidate_mask=label.candidate_mask,
                            null_pos=label.null_pos))
        return out

    def __len__(self):
        return len(self.samples) * self.repeat

    # ------------------------------------------------------------------ #
    # Light feature read (CLS only — np.load is lazy, scale_k/v untouched)
    # ------------------------------------------------------------------ #
    def _load_dino_cls(self, index):
        """Return dino_cls [T, 1024] float32 (the symmetric retrieval-key space)."""
        with np.load(self.trajectory_feature_path[index]) as data:
            return data['dino_cls'].astype(np.float32)

    def _load_images(self, rgb_dir, frame_indices):
        """Load + LingBot-preprocess RGB frames -> tensor [N, 3, H, W] in [0, 1]."""
        paths = [os.path.join(rgb_dir, f"{int(i)}.jpg") for i in frame_indices]
        return self._load_and_preprocess(
            paths, mode=self.preprocess_mode, image_size=self.image_size, patch_size=self.patch_size
        )

    def _load_image_path(self, path):
        """Load + LingBot-preprocess a single image by absolute path -> [3, H, W]."""
        return self._load_and_preprocess(
            [path], mode=self.preprocess_mode, image_size=self.image_size, patch_size=self.patch_size
        )[0]

    # ------------------------------------------------------------------ #
    # action label + goal-relative pose (no critic — collision is geometric at eval)
    # ------------------------------------------------------------------ #
    def _build_actions(self, extrinsics, base_extrinsic, pred_digit):
        """`extrinsics` = ordered segment current->goal (index 0 = current).
        Returns (pred_actions [predict_size,3] ×4 deltas, goal_rel_pose [3] = goal
        (x,y,θ) relative to current — GT for the revisit aux-pose head)."""
        L = extrinsics.shape[0]
        target_local_points, _, _, _, action_indexes = self.process_actions(
            extrinsics, base_extrinsic, 0, L - 1, pred_digit=pred_digit)
        init_vector = target_local_points[1] - target_local_points[0]
        target_xyt = self.xyz_to_xyt(target_local_points, init_vector)
        pred_xyt = target_xyt[action_indexes]                       # [predict_size+1, 3]
        # aux GT = the TRUE goal (full-path endpoint), not pred_xyt[-1] which is the
        # action-horizon-truncated waypoint (~96 steps) for long revisit segments.
        goal_rel_pose = target_xyt[-1].astype(np.float32).copy()    # goal pose rel to current
        pred_actions = (pred_xyt[1:] - pred_xyt[:-1]) * 4.0         # [predict_size, 3] deltas
        return pred_actions, goal_rel_pose

    # ------------------------------------------------------------------ #
    def __getitem__(self, index):
        s = self.samples[index % len(self.samples)]
        ti = s['traj_idx']
        k = s['k']
        goal_step = s['goal_step']

        (
            _camera_intrinsic,
            base_extrinsic,
            extrinsics,            # [T_pq, 4, 4] camera-to-world per frame
            traj_len_parquet,
        ) = self.process_data_parquet(ti)

        dino_cls = self._load_dino_cls(ti)                 # [T_f, 1024]
        T = int(min(traj_len_parquet, dino_cls.shape[0]))
        # cache/parquet should cover the whole episode; clamp defensively.
        k = min(k, T - 2)
        goal_step = min(goal_step, T - 1)

        pred_digit = np.random.randint(2, 8) if self.random_digit else self.pred_digit

        # --- retrieval keys: CLS of every observed frame [0..k] ---
        mem_cls = dino_cls[: k + 1].copy()                 # [k+1, 1024]
        # multi-positive label over mem_cls[0..k] (aligned index i <-> frame i).
        pos_mask = s['pos_mask'][: k + 1]
        neg_mask = s['neg_mask'][: k + 1]
        candidate_mask = s['candidate_mask'][: k + 1]

        # --- action segment: forward path current(k) -> goal(goal_step) ---
        seg = extrinsics[k : goal_step + 1].copy()         # seg[0] == current frame k
        pred_actions, goal_rel_pose = self._build_actions(seg, base_extrinsic, pred_digit)

        # --- raw images (LingBot-preprocessed): always needed every sample ---
        rgb_dir = self.trajectory_rgb_dir[ti]
        window_idx = list(range(k - self.window_size + 1, k + 1))  # [k-W+1 .. k]
        window_images = self._load_images(rgb_dir, window_idx)     # [W, 3, H, W]
        goal_image = self._load_image_path(s['goal_img_path'])     # real goal_{j+1}.jpg [3, H, W]

        return {
            # light tensors
            'mem_cls': torch.tensor(mem_cls, dtype=torch.float32),
            # multi-positive retrieval label (over real frames [0..k]) + null flag
            'pos_mask': torch.from_numpy(np.ascontiguousarray(pos_mask)),    # [k+1] bool
            'neg_mask': torch.from_numpy(np.ascontiguousarray(neg_mask)),    # [k+1] bool
            'candidate_mask': torch.from_numpy(np.ascontiguousarray(candidate_mask)),
            'null_pos': torch.tensor(bool(s['null_pos'])),                   # scalar bool
            'is_revisit': torch.tensor(float(s['goal_kind'] == 'revisit'), dtype=torch.float32),
            'pred_actions': torch.tensor(pred_actions, dtype=torch.float32),
            'goal_rel_pose': torch.tensor(goal_rel_pose, dtype=torch.float32),   # aux pose GT
            # raw images for the on-the-fly dense DINO + GCT window-forward.
            #   goal_cls is NOT cached for real goal images — the policy computes it
            #   from goal_image via the frozen context-free DINO trunk.
            'goal_image': goal_image,                       # [3, H, W]
            'window_images': window_images,                 # [W, 3, H, W]  (current local window [k-W+1..k])
            # pointers for the policy (loaded on GPU, per sample):
            #   - KV cache (scale_k/v, anchor_k/v) for the GCT window-forward
            #   - rgb_dir = path to ALL historical frames: load any retrieved
            #     match's image lazily as rgb_dir/<idx>.jpg
            'cache_path': self.trajectory_feature_path[ti],
            'rgb_dir': rgb_dir,
            'cur_step': int(k),
            'goal_step': int(goal_step),
        }


def memnav_collate_fn(batch):
    """Stack light tensors; pad variable-length mem_cls + retrieval masks; keep
    pointers as lists. ``mem_mask`` is the structural retrieval-candidate mask:
    early unreconstructable frames and padding are False. Label ignore-band frames
    remain retrieval candidates but are absent from pos_mask/neg_mask."""
    B = len(batch)
    D = batch[0]['mem_cls'].shape[-1]
    lengths = [b['mem_cls'].shape[0] for b in batch]
    Lmax = max(lengths)

    mem_cls = torch.zeros(B, Lmax, D, dtype=torch.float32)
    mem_mask = torch.zeros(B, Lmax, dtype=torch.bool)
    pos_mask = torch.zeros(B, Lmax, dtype=torch.bool)
    neg_mask = torch.zeros(B, Lmax, dtype=torch.bool)
    for i, b in enumerate(batch):
        Li = lengths[i]
        mem_cls[i, :Li] = b['mem_cls']
        mem_mask[i, :Li] = b['candidate_mask']
        pos_mask[i, :Li] = b['pos_mask']
        neg_mask[i, :Li] = b['neg_mask']

    return {
        'batch_mem_cls':         mem_cls,
        'batch_mem_mask':        mem_mask,
        # multi-positive retrieval label over real frames [0..Lmax-1] (+ null flag)
        'batch_pos_mask':        pos_mask,
        'batch_neg_mask':        neg_mask,
        'batch_null_pos':        torch.stack([b['null_pos'] for b in batch]),          # [B] bool
        'batch_is_revisit':      torch.stack([b['is_revisit'] for b in batch]),        # [B] float
        'batch_labels':          torch.stack([b['pred_actions'] for b in batch]),
        'batch_goal_rel_pose':   torch.stack([b['goal_rel_pose'] for b in batch]),     # aux pose GT
        # raw images (goal_cls is computed from batch_goal_image in the policy)
        'batch_goal_image':      torch.stack([b['goal_image'] for b in batch]),        # [B, 3, H, W]
        'batch_window_images':   torch.stack([b['window_images'] for b in batch]),     # [B, W, 3, H, W]
        # pointers (lists, length B) — the policy loads cache + lazy match frames per sample
        'cache_paths':           [b['cache_path'] for b in batch],
        'rgb_dirs':              [b['rgb_dir'] for b in batch],
        'cur_steps':             [b['cur_step'] for b in batch],
        'goal_steps':            [b['goal_step'] for b in batch],
    }


