"""Closed-loop 2-leg image-goal evaluation in Habitat (client half).

Drives a navigation server (memnav_server.py wire contract) through generated
two-leg episodes (MemNavData/generate_twoleg.py output):

  leg 1 (start -> A): either REPLAY the generated frames into the server's
    memory (isolates leg-2 recall: memory contents are deterministic), or
    POLICY-driven with goal image = the un-perturbed A-arrival frame
    rgb/{switch-1}.jpg (train-consistent: that is exactly the goal-A sample
    construction in memnav_dataset_lerobot).
  leg 2 (A -> B): always policy-driven. Goal image = goal_1.jpg (the
    generator's perturbed revisit view); goal position = meta goals[0].pos.

Success is DISTANCE-ONLY (<= --success_dist, default 1.0 m), matching the
Habitat ImageNav convention. SPL uses the episode's leg geodesics.

Waypoint decode (must match InternNav memnav label construction): the server
returns metre-space waypoints in the CURRENT camera planar frame, x forward,
y left. Habitat mapping (yaw psi about +Y, camera fwd = (-sin, -cos) in xz):
    dx_hab = -x*sin(psi) - y*cos(psi)
    dz_hab = -x*cos(psi) + y*sin(psi)
(derivation: label = [rel[1], -rel[0]] of the data-Z-up relative pose; both
unit checks — pure-forward and pure-left displacement — round-trip exactly.)

Run (habitat env):
  conda activate habitat
  python eval_2leg_habitat.py --episode_root /home/asus/Research/Nav/memnav_viz/mp3d_2leg \
      --scene /home/asus/Research/datasets/mp3d/17DRP5sb8fy.glb --port 18888 \
      --out ./eval2leg_memnav_warm
"""

import argparse
import csv
import glob
import io
import json
import os

import numpy as np
import requests
from PIL import Image

from generate_twoleg import (M_W, geodesic, make_sim, render, yaw_facing)

parser = argparse.ArgumentParser()
parser.add_argument("--episode_root", type=str, required=True,
                    help="dir containing episode_XXXX/ generated by generate_twoleg.py")
parser.add_argument("--scene", type=str, required=True, help="MP3D .glb (navmesh recomputed)")
parser.add_argument("--port", type=int, default=18888)
parser.add_argument("--host", type=str, default="localhost")
parser.add_argument("--out", type=str, default="./eval2leg_out")
parser.add_argument("--leg1_mode", choices=["replay", "policy"], default="replay")
parser.add_argument("--reset_memory", action="store_true",
                    help="cold arm: wipe server memory at the A->B switch")
parser.add_argument("--success_dist", type=float, default=1.0)
parser.add_argument("--max_steps", type=int, default=1200, help="frame budget per policy leg")
parser.add_argument("--exec_horizon", type=int, default=8, help="frames between replans")
parser.add_argument("--stuck_window", type=int, default=150)
parser.add_argument("--stuck_dist", type=float, default=0.10)
parser.add_argument("--agent_radius", type=float, default=0.30)
parser.add_argument("--v_max", type=float, default=0.0376, help="m per frame (data-gen cruise)")
parser.add_argument("--r_min", type=float, default=0.40)
parser.add_argument("--max_turn_deg", type=float, default=4.5)
parser.add_argument("--lookahead", type=float, default=0.7)
parser.add_argument("--episodes", type=int, default=0, help="cap #episodes (0 = all)")
parser.add_argument("--save_video", action="store_true")
args = parser.parse_args()

BASE = f"http://{args.host}:{args.port}"
CAM_H = 0.5


# --------------------------------------------------------------------------- #
# HTTP helpers
# --------------------------------------------------------------------------- #
def jpg_bytes(rgb):
    buf = io.BytesIO()
    Image.fromarray(rgb).save(buf, format="JPEG", quality=95)
    return buf.getvalue()


def srv_reset(camera_height=CAM_H):
    r = requests.post(f"{BASE}/navigator_reset", json={"camera_height": camera_height})
    r.raise_for_status()
    return r.json()["algo"]


def srv_memory(image_jpg):
    r = requests.post(f"{BASE}/memory_step", files={"image": ("image.jpg", image_jpg)})
    r.raise_for_status()
    return r.json()


def srv_plan(image_jpg, goal_jpg):
    r = requests.post(f"{BASE}/imagegoal_step",
                      files={"image": ("image.jpg", image_jpg), "goal": ("goal.jpg", goal_jpg)})
    r.raise_for_status()
    return r.json()


# --------------------------------------------------------------------------- #
# geometry
# --------------------------------------------------------------------------- #
def data_to_hab(p):
    return M_W.T @ np.asarray(p, float)


def waypoints_to_world(way, pos_xz, psi):
    """[K,3] label-frame waypoints (m; x fwd, y left) -> [K,2] habitat xz world."""
    out = np.zeros((len(way), 2))
    s, c = np.sin(psi), np.cos(psi)
    for i, (lx, ly, _th) in enumerate(way):
        out[i, 0] = pos_xz[0] + (-lx * s - ly * c)
        out[i, 1] = pos_xz[1] + (-lx * c + ly * s)
    return out


def parquet_pose_hab(row_action):
    """parquet `action` (4x4 cam-to-world, data Z-up) -> (floor_pos_hab[3], yaw)."""
    Td = np.stack([np.asarray(r, dtype=np.float64) for r in row_action]).reshape(4, 4)
    p_h = M_W.T @ Td[:3, 3]
    R_h = M_W.T @ Td[:3, :3]           # rot_y(yaw)
    yaw = float(np.arctan2(R_h[0, 2], R_h[2, 2]))
    floor = p_h - np.array([0.0, CAM_H, 0.0])
    return floor, yaw


def pursuit_step(pos, psi, path_xz, pf):
    """One kinematic step (v/turn caps of the data-gen controller) toward a world
    polyline. Returns (new_pos, new_psi, step_len)."""
    xz = np.array([pos[0], pos[2]])
    d = np.linalg.norm(path_xz - xz[None, :], axis=1)
    ahead = np.where(d >= args.lookahead)[0]
    tgt = path_xz[ahead[0]] if len(ahead) else path_xz[-1]
    alpha = (yaw_facing(tgt - xz) - psi + np.pi) % (2 * np.pi) - np.pi
    v = args.v_max * (0.48 + 0.52 * (1 + np.cos(alpha)) / 2)
    kappa = np.clip(2.0 * alpha / args.lookahead, -1.0 / args.r_min, 1.0 / args.r_min)
    mturn = np.deg2rad(args.max_turn_deg)
    psi_new = psi + float(np.clip(kappa * v, -mturn, mturn))
    fwd = np.array([-np.sin(psi_new), 0.0, -np.cos(psi_new)])
    cand = pos + v * fwd
    snap = np.array(pf.snap_point(cand), float)
    if not np.isfinite(snap).all() or np.linalg.norm(snap[[0, 2]] - cand[[0, 2]]) > 0.06:
        cand2 = pos + 0.3 * v * fwd                      # creep when grazing geometry
        snap2 = np.array(pf.snap_point(cand2), float)
        if np.isfinite(snap2).all() and np.linalg.norm(snap2[[0, 2]] - cand2[[0, 2]]) <= 0.06:
            return snap2, psi_new, 0.3 * v
        return pos, psi_new, 0.0                         # rotate in place (blocked)
    return snap, psi_new, v


# --------------------------------------------------------------------------- #
# rollout
# --------------------------------------------------------------------------- #
def run_policy_leg(sim, pf, pos, psi, goal_jpg, goal_xz, geo_dist, writer=None):
    """Policy-driven leg. Returns dict(reached, path_len, end_pos, end_psi, steps)."""
    path_len, history, way_world, plans = 0.0, [], None, []
    for step in range(args.max_steps):
        rgb, _depth = render(sim, pos + np.array([0, CAM_H, 0]), psi)
        frame = jpg_bytes(rgb)
        if writer is not None:
            writer.append_data(rgb)
        if step % args.exec_horizon == 0:
            resp = srv_plan(frame, goal_jpg)
            if "trajectory" in resp:
                way = np.asarray(resp["trajectory"], float)
                way_world = waypoints_to_world(way, [pos[0], pos[2]], psi)
                plans.append(dict(step=step, gate=resp.get("gate"),
                                  match_idx=resp.get("match_idx"), anchor=resp.get("anchor"),
                                  raw_score=resp.get("raw_score"),
                                  frame_idx=resp.get("frame_idx")))
        else:
            srv_memory(frame)
        if way_world is not None:
            pos, psi, dl = pursuit_step(pos, psi, way_world, pf)
            path_len += dl
        history.append(np.array([pos[0], pos[2]]))
        if np.linalg.norm(np.array([pos[0], pos[2]]) - goal_xz) < args.success_dist:
            return dict(reached=True, path_len=path_len, end_pos=pos, end_psi=psi, steps=step + 1, plans=plans)
        if len(history) > args.stuck_window and \
           np.linalg.norm(history[-1] - history[-args.stuck_window]) < args.stuck_dist:
            return dict(reached=False, path_len=path_len, end_pos=pos, end_psi=psi, steps=step + 1, plans=plans)
    return dict(reached=False, path_len=path_len, end_pos=pos, end_psi=psi, steps=args.max_steps, plans=plans)


def spl(reached, geo, plen):
    return float(np.clip(geo / max(plen, 1e-6), 0, 1)) * float(reached)


def main():
    os.makedirs(args.out, exist_ok=True)
    try:
        import imageio
    except ImportError:
        imageio = None

    ep_dirs = sorted(d for d in glob.glob(os.path.join(args.episode_root, "episode_*"))
                     if os.path.isfile(os.path.join(d, "meta", "gen_meta.json")))
    if args.episodes:
        ep_dirs = ep_dirs[:args.episodes]

    sim = make_sim(args.scene, "", agent_radius=args.agent_radius)
    pf = sim.pathfinder
    algo = srv_reset()
    print(f"[eval2leg] server algo={algo}, {len(ep_dirs)} episodes, "
          f"leg1={args.leg1_mode}, cold={args.reset_memory}")

    metrics = []
    for ep_dir in ep_dirs:
        meta = json.load(open(os.path.join(ep_dir, "meta", "gen_meta.json")))
        if meta.get("n_legs", 2) != 2:
            continue
        import pandas as pd
        rows = pd.read_parquet(os.path.join(ep_dir, "data/chunk-000/episode_000000.parquet"))
        switch = int(meta["switch_idx"])
        rgb_dir = os.path.join(ep_dir, "videos/chunk-000/observation.images.rgb")

        A_hab = data_to_hab(meta["A"])
        B = meta["goals"][0]
        B_hab = data_to_hab(B["pos"])
        A_xz, B_xz = A_hab[[0, 2]], B_hab[[0, 2]]
        start_floor, start_psi = parquet_pose_hab(rows.iloc[0]["action"])
        okA, geoA, _ = geodesic(pf, start_floor, np.array([A_xz[0], start_floor[1], A_xz[1]]))
        okB, geoB, _ = geodesic(pf, np.array([A_xz[0], start_floor[1], A_xz[1]]),
                                np.array([B_xz[0], start_floor[1], B_xz[1]]))

        goalA_jpg = open(os.path.join(rgb_dir, f"{switch - 1}.jpg"), "rb").read()
        goalB_jpg = open(os.path.join(ep_dir, "goal_1.jpg"), "rb").read()

        srv_reset(camera_height=float(meta.get("camera_height_m", CAM_H)))
        writer = None
        if args.save_video and imageio is not None:
            writer = imageio.get_writer(
                os.path.join(args.out, os.path.basename(ep_dir) + ".mp4"), fps=10)

        # ---- leg 1 ----
        if args.leg1_mode == "replay":
            for i in range(switch):
                srv_memory(open(os.path.join(rgb_dir, f"{i}.jpg"), "rb").read())
            pos, psi = parquet_pose_hab(rows.iloc[switch - 1]["action"])
            legA = dict(reached=True, path_len=geoA, steps=switch, plans=[])   # scripted: SPL_A undefined
        else:
            legA = run_policy_leg(sim, pf, start_floor, start_psi, goalA_jpg, A_xz, geoA, writer)
            pos, psi = legA["end_pos"], legA["end_psi"]

        # ---- leg 2 ----
        legB = dict(reached=False, path_len=0.0, steps=0, plans=[])
        if legA["reached"]:
            if args.reset_memory:
                srv_reset(camera_height=float(meta.get("camera_height_m", CAM_H)))
            legB = run_policy_leg(sim, pf, pos, psi, goalB_jpg, B_xz, geoB, writer)

        if writer is not None:
            writer.close()
        m = dict(
            episode=os.path.basename(ep_dir),
            reached_A=float(legA["reached"]), reached_B=float(legB["reached"]),
            spl_A=(spl(legA["reached"], geoA, legA["path_len"])
                   if args.leg1_mode == "policy" else float("nan")),
            spl_B=spl(legB["reached"], geoB, legB["path_len"]),
            geo_A=geoA, geo_B=geoB,
            len_A=legA["path_len"], len_B=legB["path_len"],
            steps_A=legA["steps"], steps_B=legB["steps"],
            covis=B.get("covis"), recall_gap=B.get("recall_gap"),
            gate_B_mean=(float(np.mean([p["gate"] for p in legB["plans"]])) if legB["plans"] else float("nan")),
            gate_B_max=(float(np.max([p["gate"] for p in legB["plans"]])) if legB["plans"] else float("nan")),
        )
        json.dump(dict(legA=legA["plans"], legB=legB["plans"]),
                  open(os.path.join(args.out, m["episode"] + "_plans.json"), "w"))
        metrics.append(m)
        print(f"[{m['episode']}] A={m['reached_A']:.0f} B={m['reached_B']:.0f} "
              f"splB={m['spl_B']:.2f} lenB={m['len_B']:.1f}/{geoB:.1f}m gateB={m['gate_B_mean']:.2f}/{m['gate_B_max']:.2f}")

        with open(os.path.join(args.out, "metric.csv"), "w", newline="") as f:
            wcsv = csv.DictWriter(f, fieldnames=list(metrics[0].keys()))
            wcsv.writeheader()
            wcsv.writerows(metrics)

    n = len(metrics)
    nA = sum(m["reached_A"] for m in metrics)
    condB = [m for m in metrics if m["reached_A"] > 0.5]
    summary = dict(
        episodes=n, leg1_mode=args.leg1_mode, cold=args.reset_memory,
        SR_A=(nA / n) if n and args.leg1_mode == "policy" else None,
        SR_B_given_A=(sum(m["reached_B"] for m in condB) / len(condB)) if condB else 0.0,
        mean_spl_B=float(np.nanmean([m["spl_B"] for m in condB])) if condB else 0.0,
    )
    json.dump(summary, open(os.path.join(args.out, "summary.json"), "w"), indent=2)
    print("[eval2leg] done:", summary)
    sim.close()


if __name__ == "__main__":
    main()
